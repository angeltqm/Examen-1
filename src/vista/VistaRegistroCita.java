    // ===== Metodos agregados para el patron MVC =====
    private List<Medico> medicosMostrados = new ArrayList<>();

    // ---------- Entradas ----------
    public String getNSS() {
        return jTextFieldNSS.getText().trim();
    }

    public String getFecha() {
        return jTextFieldFecha.getText().trim();
    }

    public String getHora() {
        return jTextFieldHora.getText().trim();
    }

    public Medico getMedicoSeleccionado() {
        int i = jListMedicos.getSelectedIndex();
        if (i < 0 || i >= medicosMostrados.size()) {
            return null;
        }
        return medicosMostrados.get(i);
    }

    public javax.swing.JButton getBtnBuscar() {
        return jButtonBuscar;
    }

    public javax.swing.JButton getBtnApartar() {
        return jButtonApartar;
    }

    public javax.swing.JList<?> getListaMedicos() {
        return jListMedicos;
    }

    public void mostrarPaciente(Paciente p) {
        jLabelPaciente.setText("Paciente: " + p.getNombreCompleto() + "   |   NSS: " + p.getNss());
    }

    public void mostrarMedicos(List<Medico> lista) {
        medicosMostrados = new ArrayList<>(lista);
        String[] nombres = new String[lista.size()];
        for (int i = 0; i < lista.size(); i++) {
            nombres[i] = lista.get(i).toString();
        }
        jListMedicos.setListData(nombres);
        jTextAreaInformacion.setText("");
    }

    public void mostrarDatosMedico(Medico m) {
        jTextAreaInformacion.setText(
                "DATOS DEL MEDICO\n"
                + "----------------------------\n"
                + "Nombre:       " + m.getNombreCompleto() + "\n"
                + "Especialidad: " + m.getEspecialidad() + "\n"
                + "Consultorio:  " + m.getConsultorio() + "\n"
                + "Dias:         " + m.getDiasConsulta() + "\n"
                + "Horas:        " + m.getHorasConsulta() + "\n");
    }

    public void mostrarCita(Cita c) {
        jTextAreaInformacion.setText(
                "CITA REGISTRADA\n"
                + "----------------------------\n"
                + "Paciente:    " + c.getPaciente().getNombreCompleto() + "\n"
                + "NSS:         " + c.getPaciente().getNss() + "\n"
                + "Medico:      " + c.getMedico().getNombreCompleto() + "\n"
                + "Consultorio: " + c.getMedico().getConsultorio() + "\n"
                + "Fecha:       " + c.getFecha() + "\n"
                + "Hora:        " + c.getHora() + "\n");
    }

    public void mostrarError(String msg) {
        javax.swing.JOptionPane.showMessageDialog(this, msg, "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
    }

